#!/usr/bin/env node
// Turns the SEO manager's redirect map (myhive-next/seo/redirect-map.csv) into
//   * prod-migration-seo-prague-urls.sql   (run once on prod after Flyway V15)
//   * a marked block at the end of src/main/resources/data-prague.sql (dev seed)
//   * re-keyed content/translations-de/*.json (so translations-to-sql.mjs keeps matching)
//
//   node scripts/seo-map-to-sql.mjs           # from myhive-backend; idempotent
//   node scripts/seo-map-to-sql.mjs --check   # validate the map and print counts only
//
// Every statement matches rows by `slug IN (old, new)`, so re-running is a no-op, and uses only
// subqueries / CURRENT_TIMESTAMP so the same text runs on Postgres and H2 (PostgreSQL mode).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const CATEGORY_COUNTS = {
  shooting: 5,
  driving: 7,
  action: 11,
  beer: 10,
  food: 9,
  boats: 3,
  nightlife: 8,
  strippers: 5,
  pranks: 11,
  transfers: 3,
};

// Copy of GONE_BLOG_SLUGS in myhive-next/lib/gone.ts (node cannot import .ts): keep in sync.
export const GONE_BLOG_SLUGS = [
  'top-5-group-travel-destinations-for-2026',
  'why-ai-is-changing-the-way-we-travel-together',
  'bali-on-a-budget-a-group-travel-guide',
  'the-rise-of-multi-traveler-experiences',
  'weekend-getaway-ideas-for-large-groups',
];

export const BLOG_RENAME = {
  oldSlug: 'how-to-plan-a-stress-free-group-trip',
  newSlug: 'how-to-plan-a-stag-do',
  newSlugDe: 'jga-planen',
};

export const BEGIN_MARKER = '-- BEGIN seo-map (generated by scripts/seo-map-to-sql.mjs)';
export const END_MARKER = '-- END seo-map';

const FIELDS = ['type', 'oldEn', 'newEn', 'oldDe', 'newDe', 'categoryEn', 'categoryDe', 'note'];
const ACTIVITY_COUNT = 72;

export function parseMap(csvText) {
  const lines = csvText
    .split('\n')
    .map((line) => line.replace(/\r$/, ''))
    .filter((line) => line.trim() !== '');
  return lines.slice(1).map((line, index) => {
    if (line.includes('"')) {
      throw new Error(`row ${index + 1}: a quote character is not supported`);
    }
    const cells = line.split(',');
    if (cells.length !== FIELDS.length) {
      throw new Error(`row ${index + 1}: expected ${FIELDS.length} fields, got ${cells.length}`);
    }
    return Object.fromEntries(FIELDS.map((field, i) => [field, cells[i].trim()]));
  });
}

export function slugOf(url) {
  return url.split('/').filter(Boolean).pop() ?? '';
}

export function validateRows(rows) {
  const activities = rows.filter((row) => row.type === 'activity');
  if (activities.length !== ACTIVITY_COUNT) {
    throw new Error(`expected ${ACTIVITY_COUNT} activity rows, got ${activities.length}`);
  }
  const seenEn = new Set();
  const seenDe = new Set();
  for (const row of activities) {
    const en = slugOf(row.newEn);
    const de = slugOf(row.newDe);
    if (seenEn.has(en)) {
      throw new Error(`duplicate new EN slug: ${en}`);
    }
    if (seenDe.has(de)) {
      throw new Error(`duplicate new DE slug: ${de}`);
    }
    seenEn.add(en);
    seenDe.add(de);
  }
  for (const row of activities) {
    const de = slugOf(row.newDe);
    if (seenEn.has(de) && de !== slugOf(row.newEn)) {
      throw new Error(`new DE slug ${de} equals a different row's new EN slug`);
    }
  }
  const counts = Object.fromEntries(Object.keys(CATEGORY_COUNTS).map((slug) => [slug, 0]));
  for (const row of activities) {
    if (!(row.categoryEn in CATEGORY_COUNTS)) {
      throw new Error(`unknown category_en "${row.categoryEn}" for ${row.newEn}`);
    }
    counts[row.categoryEn]++;
  }
  for (const [slug, expected] of Object.entries(CATEGORY_COUNTS)) {
    if (counts[slug] !== expected) {
      throw new Error(`category ${slug}: expected ${expected} activities, got ${counts[slug]}`);
    }
  }
  // A guard rule redirects every old slug, so an old slug that is another page's live slug would
  // send that page away. A row keeping its own slug (old == its own new) is fine.
  for (const row of activities) {
    const old = slugOf(row.oldEn);
    for (const other of rows) {
      if (other === row) {
        continue;
      }
      if (old === slugOf(other.newEn) || old === slugOf(other.newDe)) {
        throw new Error(`old slug ${old} equals the new slug of ${other.newEn || other.newDe}: would redirect a live page`);
      }
    }
  }
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

export function activityUpdate(row) {
  const oldEn = slugOf(row.oldEn);
  const newEn = slugOf(row.newEn);
  const newDe = slugOf(row.newDe);
  return [
    `UPDATE activities SET slug = ${q(newEn)}, slug_de = ${q(newDe)},`,
    `  primary_category_id = (SELECT id FROM primary_categories WHERE slug = ${q(row.categoryEn)}),`,
    '  updated_at = CURRENT_TIMESTAMP',
    "WHERE destination_id = (SELECT id FROM destinations WHERE slug = 'prague')",
    `  AND slug IN (${q(oldEn)}, ${q(newEn)});`,
  ].join('\n');
}

export function blogUpdates() {
  const { oldSlug, newSlug, newSlugDe } = BLOG_RENAME;
  return [
    `UPDATE blog_posts SET slug = ${q(newSlug)}, slug_de = ${q(newSlugDe)}, updated_at = CURRENT_TIMESTAMP`,
    `WHERE slug IN (${q(oldSlug)}, ${q(newSlug)});`,
    `DELETE FROM blog_posts WHERE slug IN (${GONE_BLOG_SLUGS.map(q).join(', ')});`,
  ].join('\n');
}

function statements(rows) {
  const updates = rows.filter((row) => row.type === 'activity').map(activityUpdate);
  return [...updates, blogUpdates()].join('\n\n');
}

export function prodSql(rows) {
  return [
    '-- Generated by scripts/seo-map-to-sql.mjs from myhive-next/seo/redirect-map.csv - do not edit by hand.',
    '-- Run once on prod AFTER Flyway V15 (slug_de / primary_categories). Idempotent: rows match slug IN (old, new).',
    'BEGIN;',
    '',
    statements(rows),
    '',
    'COMMIT;',
    '',
  ].join('\n');
}

export function devBlock(rows) {
  return [
    BEGIN_MARKER,
    statements(rows),
    '',
    '-- dev only: make the Prague hub indexable so the local sitemap/smoke checks list it',
    "UPDATE destinations SET seo_indexable = TRUE WHERE slug = 'prague';",
    END_MARKER,
  ].join('\n');
}

export function rekey(jsonObject, renames) {
  const out = { ...jsonObject };
  for (const section of ['activities', 'blog']) {
    if (!jsonObject[section]) {
      continue;
    }
    out[section] = Object.fromEntries(
      Object.entries(jsonObject[section]).map(([key, value]) => [renames.get(key) ?? key, value])
    );
  }
  return out;
}

export function renameMap(rows) {
  const renames = new Map(
    rows.filter((row) => row.type === 'activity').map((row) => [slugOf(row.oldEn), slugOf(row.newEn)])
  );
  renames.set(BLOG_RENAME.oldSlug, BLOG_RENAME.newSlug);
  return renames;
}

// Re-encodes LF text with the EOL of the file it replaces (CRLF when there is none: repo default).
export function withEol(text, existingText) {
  const eol = existingText !== null && !existingText.includes('\r\n') && existingText.includes('\n') ? '\n' : '\r\n';
  return text.replace(/\r\n/g, '\n').replace(/\n/g, eol);
}

export function replaceBlock(fileText, block) {
  const eol = fileText.includes('\r\n') ? '\r\n' : '\n';
  const text = fileText.replace(/\r\n/g, '\n');
  const start = text.indexOf(BEGIN_MARKER);
  const end = text.indexOf(END_MARKER);
  let next;
  if (start >= 0 && end > start) {
    next = text.slice(0, start) + block + text.slice(end + END_MARKER.length);
  } else {
    next = `${text.replace(/\n*$/, '')}\n\n${block}\n`;
  }
  return next.replace(/\n/g, eol);
}

function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const csvPath = path.resolve(root, '..', 'myhive-next', 'seo', 'redirect-map.csv');
  const rows = parseMap(readFileSync(csvPath, 'utf8'));
  validateRows(rows);
  const activities = rows.filter((row) => row.type === 'activity');
  console.log(`map ok: ${rows.length} rows, ${activities.length} activities`);
  for (const slug of Object.keys(CATEGORY_COUNTS)) {
    console.log(`  ${slug}: ${activities.filter((row) => row.categoryEn === slug).length}`);
  }
  if (process.argv.includes('--check')) {
    return;
  }

  const prodFile = path.join(root, 'prod-migration-seo-prague-urls.sql');
  writeFileSync(prodFile, withEol(prodSql(rows), existsSync(prodFile) ? readFileSync(prodFile, 'utf8') : null));
  console.log(`${prodFile}: ${activities.length} activity updates + blog statements`);

  const pragueFile = path.join(root, 'src', 'main', 'resources', 'data-prague.sql');
  writeFileSync(pragueFile, replaceBlock(readFileSync(pragueFile, 'utf8'), devBlock(rows)));
  console.log(`${pragueFile}: seo-map block written`);

  const renames = renameMap(rows);
  for (const name of ['activities-prague-1', 'activities-prague-2', 'activities-prague-3', 'common']) {
    const file = path.join(root, 'content', 'translations-de', `${name}.json`);
    if (!existsSync(file)) {
      throw new Error(`missing ${file}`);
    }
    const original = readFileSync(file, 'utf8');
    const eol = original.includes('\r\n') ? '\r\n' : '\n';
    const json = `${JSON.stringify(rekey(JSON.parse(original), renames), null, 2)}\n`.replace(/\n/g, eol);
    writeFileSync(file, json);
    console.log(`${file}: re-keyed`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    main();
  } catch (error) {
    console.error(`seo-map-to-sql: ${error.message}`);
    process.exit(1);
  }
}
